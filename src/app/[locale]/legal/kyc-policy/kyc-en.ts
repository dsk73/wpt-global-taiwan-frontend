const kycEn = `As a licensed operator abiding by the law and applicable regulations, we are obliged to verify the identity of our players and prevent problem activity or fraud. This requires all players to provide some documentation when requested.

### When is KYC required?

- On **deposit**, this may be requested using a risk-based approach.
- On **withdrawal**, full KYC (customer due diligence) will almost always be required.

### What documents are needed to successfully verify a player?

There are three types of documentation that may be requested: proof of identity (POI), address (POD) and deposit (POD).

1. For **proof of identity**, we require one of the following (government-issued):
   - ID Card
   - Passport
   - Driver’s licence
   - **Further requirements:**
     - Clear, color picture with all four corners visible
     - Visible **expiry date** (with the document’s expiry date at least 3 months in the future)
     - Visible **date of issue, signature, full name,** and **date of birth** (player must be 18 years of age or above)

2. For **proof of address**, we require:
   - Utility bill
   - Bank statement
   - **Further requirements:**
     - Clear, color picture with all four corners visible
     - Visible **date of issue** (the document must not be more than three months old)
     - Visible **address**

3. For **proof of deposit**:
   - If using a **credit card**, we require a clear, color picture of the front and back of the card
     - The first 6 digits and last 4 digits must be visible (remember to hide the middle digits on the front and the CVV number on the back of the card)
     - The card must be signed
     - The account name must be visible
     - For embossed cards, only the first 6 digits and last 4 digits must be visible on the back
   - If using a **wallet**, we require a screenshot proving wallet ownership
     - The website URL must be visible
     - The account name must be visible
     - The player’s email or name must be visible
     - The deposit transaction must be visible

### Further Information

WPT Global follows a risk-based approach and may perform checks at an earlier stage if this is deemed necessary.

All documentation is held electronically and confidentially against customers’ account details. Our fraud, risk and poker security departments have access to a variety of databases and reports which are used to review players.

All employees in customer-facing roles are familiar with the above policy and procedure and communicate any important information and address queries to the MLRO.
`;

